def pe_flag(country_code: str, fallback_flag: str = "🏳️") -> str:
    """Return premium flag emoji HTML for Telegram messages.

    country_code should be a 2-letter country/region code like IN, US, GB.
    If a premium flag ID is not available, it safely returns the normal flag.
    """
    code = str(country_code or "").strip().upper()
    flag_data = FLAG_EMOJIS.get(code)
    if not flag_data:
        return html.escape(fallback_flag or "🏳️")
    fallback, emoji_id = flag_data
    return f'<tg-emoji emoji-id="{html.escape(str(emoji_id), quote=True)}">{html.escape(fallback)}</tg-emoji>'


def pe(name: str, fallback_name: str = "star") -> str:
    """Return a premium emoji HTML tag for Telegram messages."""
    fallback, emoji_id = PREMIUM_EMOJIS.get(name, PREMIUM_EMOJIS[fallback_name])
    return f'<tg-emoji emoji-id="{html.escape(str(emoji_id), quote=True)}">{html.escape(fallback)}</tg-emoji>'


def pe_id(name: str, fallback_name: str = "star") -> str:
    """Return only custom_emoji_id. Use this for inline button icons."""
    return PREMIUM_EMOJIS.get(name, PREMIUM_EMOJIS[fallback_name])[1]


